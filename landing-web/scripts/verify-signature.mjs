import { mkdir, writeFile } from 'node:fs/promises';
process.on('unhandledRejection', error => { console.error(error); process.exit(1); });
const base = process.env.LANDING_QA_BASE || 'http://localhost:3100';
const output = process.argv[2];
await mkdir(output, { recursive: true });
const targets = await (await fetch('http://localhost:9317/json/list')).json();
const target = targets.find(t => t.type === 'page');
const socket = new WebSocket(target.webSocketDebuggerUrl);
await new Promise(resolve => socket.addEventListener('open', resolve, { once: true }));
let seq = 0;
const pending = new Map();
const failures = [];
socket.addEventListener('message', ({ data }) => {
  const msg = JSON.parse(data);
  if (msg.id) { const p = pending.get(msg.id); pending.delete(msg.id); if (msg.error) p.reject(new Error(JSON.stringify(msg.error))); else p.resolve(msg.result); }
  else if (msg.method === 'Runtime.exceptionThrown') failures.push(msg.params.exceptionDetails.text);
});
const call = (method, params = {}) => new Promise((resolve, reject) => { const id = ++seq; pending.set(id, {resolve, reject}); socket.send(JSON.stringify({id, method, params})); });
const evaluate = async expression => { const r = await call('Runtime.evaluate', {expression, returnByValue:true, awaitPromise:true}); if (r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
const sleep = ms => new Promise(r => setTimeout(r, ms));
const assert = (value, description) => { if (!value) throw new Error(description); };
const waitFor = async expression => { for (let i=0;i<100;i++) { if (await evaluate(expression)) return; await sleep(100); } throw new Error('Timed out: '+expression); };
const click = async label => { assert(await evaluate(`(() => {const e=[...document.querySelectorAll('button')].find(b => b.textContent.trim()===${JSON.stringify(label)} || b.getAttribute('aria-label')===${JSON.stringify(label)} || (${JSON.stringify(label)}==='되돌리기'&&b.getAttribute('aria-label')==='마지막 획 되돌리기')); if(!e || e.disabled) return false; e.click(); return true;})()`), 'button '+label); await sleep(200); };
const shot = async name => {await sleep(400); const {data} = await call('Page.captureScreenshot',{format:'png'});await writeFile(`${output}/${name}.png`, Buffer.from(data,'base64'));};
await call('Page.enable'); await call('Runtime.enable');
await call('Network.enable'); await call('Network.setCacheDisabled', { cacheDisabled: true });
const report=[];
for(const [name,width,height,mobile] of [['desktop',1280,900,false],['tablet',960,900,false],['mobile',390,844,true],['mobile-short',390,600,true]]) {
  await call('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile});
  await call('Page.navigate',{url:base});
  await waitFor(`document.querySelector('button') && document.readyState === 'complete'`);
  await sleep(2000);
  const hero = await evaluate(`(() => {const v=document.querySelector('[aria-label="찰캌 앱 화면"]');return [...v.querySelectorAll('img')].filter(i=>i.getBoundingClientRect().width>0).map(i=>({alt:i.alt,loaded:i.complete&&i.naturalWidth>0}));})()`);
  assert(hero.length === (mobile?1:width<=960?2:3) && hero.every(i=>i.loaded),name+' hero screens');
  assert(await evaluate(`document.documentElement.scrollWidth <= window.innerWidth`),name+' page overflow');
  await shot(name+'-hero');
  await evaluate(`document.getElementById('experience').scrollIntoView({behavior:'instant',block:'start'})`);
  await click('카메라 들기'); await click('찍기'); await waitFor(`!!document.querySelector('dialog[open]')`);
  await click('이 한 장으로'); await waitFor(`!!document.querySelector('canvas[aria-label="사인 입력창"]')`);
  assert(await evaluate(`!document.querySelector('img[alt="내 사인"]')`),'empty signature');
  assert(await evaluate(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='이 사인으로 할래요').disabled`),'empty signature cannot continue');
  await shot(name+'-signature-empty');
  const rect=await evaluate(`(() => {const r=document.querySelector('canvas[aria-label="사인 입력창"]').getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height};})()`);
  const x=rect.x+rect.width*.25,y=rect.y+rect.height*.45;
  await call('Input.dispatchMouseEvent',{type:'mouseMoved',x,y});
  await call('Input.dispatchMouseEvent',{type:'mousePressed',x,y,button:'left',buttons:1,clickCount:1});
  for(let i=1;i<=20;i++) await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:x+rect.width*.5*i/20,y:y+Math.sin(i/20*Math.PI*2)*rect.height*.12,button:'left',buttons:1});
  await call('Input.dispatchMouseEvent',{type:'mouseReleased',x:x+rect.width*.5,y,button:'left',buttons:0,clickCount:1});
  await sleep(200);
  assert(await evaluate(`!Array.from(document.querySelectorAll('button')).find(b=>b.getAttribute('aria-label')==='마지막 획 되돌리기' || b.textContent.trim()==='되돌리기').disabled`),'pointer stroke');
  await shot(name+'-signature-drawn');
  await click('되돌리기'); await click('예시 사인으로 채우기'); await click('전체 지우기');
  assert(await evaluate(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='이 사인으로 할래요').disabled`),'clear disables continuation');
  await click('예시 사인으로 채우기');
  const bounds=await evaluate(`(() => {const d=document.querySelector('dialog[open]'), r=d.getBoundingClientRect(); return {height:r.height,view:innerHeight,scroll:d.scrollHeight,client:d.clientHeight,buttons:[...d.querySelectorAll('button')].map(b=>({text:b.textContent.trim(),height:b.getBoundingClientRect().height,bottom:b.getBoundingClientRect().bottom}))};})()`);
  assert(bounds.scroll<=bounds.client+1,name+' signature sheet has no scroll');
  assert(bounds.buttons.every(b=>b.height>=44 && b.bottom<=height),name+' buttons fit');
  await click('이 사인으로 할래요'); await waitFor(`document.querySelector('dialog[open]')?.textContent.includes('이렇게 보여요')`);
  assert(await evaluate(`(()=>{const d=document.querySelector('dialog[open]');return d.scrollHeight<=d.clientHeight+1 && [...d.querySelectorAll('button')].every(b=>b.getBoundingClientRect().bottom<=innerHeight)})()`),'preview fits viewport');
  await shot(name+'-signature-preview');
  await click('다시 그리기');
  assert(await evaluate(`!Array.from(document.querySelectorAll('button')).find(b=>b.getAttribute('aria-label')==='마지막 획 되돌리기' || b.textContent.trim()==='되돌리기').disabled`),'redraw retains strokes');
  await click('이 사인으로 할래요'); await click('전시하기');
  await waitFor(`!!document.querySelector('img[alt="내 사인"]')`); await sleep(1200);
  const signature=await evaluate(`document.querySelector('img[alt="내 사인"]').src`);
  assert(signature.startsWith('data:image/png;base64,'),'local png');
  const pngSize=await evaluate(`new Promise(resolve=>{const i=new Image();i.onload=()=>resolve([i.width,i.height]);i.src=${JSON.stringify(signature)}})`);
  assert(pngSize[0]===1024&&pngSize[1]===512,'signature PNG dimensions');
  await evaluate(`document.querySelector('img[alt="내 사인"]').closest('ul').scrollIntoView({behavior:'instant',block:'start'})`);
  await shot(name+'-reveal');
  await click('다시 찍어보기'); await click('찍기');await waitFor(`!!document.querySelector('dialog[open]')`); await click('이 한 장으로'); await click('이 사인으로 할래요');await click('전시하기');
  await waitFor(`!!document.querySelector('img[alt="내 사인"]')`);
  assert(await evaluate(`document.querySelector('img[alt="내 사인"]').src===${JSON.stringify(signature)}`),'retake retains signature');
  await evaluate(`document.getElementById('how').scrollIntoView({behavior:'instant',block:'start'})`); await sleep(1800);
  const guide=await evaluate(`Array.from(document.querySelectorAll('#how img')).map(i=>({src:i.getAttribute('src'),loaded:i.complete&&i.naturalWidth>0}))`);
  assert(guide.length===5 && guide.every(i=>i.loaded),name+' guide five actual screenshots');
  await shot(name+'-guide');
  assert(await evaluate(`document.documentElement.scrollWidth <= window.innerWidth`),name+' final overflow');
  report.push({name,width,height,hero,guide,signatureBytes:signature.length,bounds,checks:'PASS'});
}
assert(failures.length===0,'browser runtime exceptions: '+failures.join(', '));
await writeFile(`${output}/browser-report.json`,JSON.stringify({base,report,failures},null,2));
console.log(JSON.stringify({report,failures},null,2));
socket.close();
